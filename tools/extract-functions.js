#!/usr/bin/env node
/**
 * Extracts the JavaScript out of every `function` node in flows.json into
 * src/functions/, one file per node, so the logic can be read and diffed
 * without importing the flow into Node-RED.
 *
 * flows.json stays the source of truth — run this after editing the flow:
 *
 *     node tools/extract-functions.js
 *
 * Pass --check to fail instead of writing when the two are out of sync
 * (useful in CI).
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FLOW = path.join(ROOT, 'flows.json');
const OUT = path.join(ROOT, 'src', 'functions');

const check = process.argv.includes('--check');

const slug = (name) =>
    name
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '');

const render = (node) => {
    const header = [
        '/**',
        ` * ${(node.name || node.id).trim()}`,
        ' *',
        ` * Body of the Node-RED function node \`${node.id}\` in flows.json,`,
        ` * wired with ${node.outputs} output${node.outputs === 1 ? '' : 's'}.`,
        ' * It runs inside Node-RED with `msg`, `node`, `flow` and `global` in scope,',
        ' * which is why it reads as a bare body rather than a module.',
        ' *',
        ' * Generated by tools/extract-functions.js — edit the flow, not this file.',
        ' */',
        '',
    ].join('\n');

    const body = node.func.replace(/\s+$/, '');
    return `${header}${body}\n`;
};

const flows = JSON.parse(fs.readFileSync(FLOW, 'utf8'));
const functions = flows.filter((n) => n.type === 'function');

fs.mkdirSync(OUT, { recursive: true });

const expected = new Map();
functions.forEach((node, i) => {
    const file = `${String(i + 1).padStart(2, '0')}-${slug(node.name || node.id)}.js`;
    expected.set(file, render(node));
});

let drifted = [];

for (const [file, contents] of expected) {
    const target = path.join(OUT, file);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (current === contents) continue;
    drifted.push(file);
    if (!check) fs.writeFileSync(target, contents);
}

for (const file of fs.readdirSync(OUT)) {
    if (expected.has(file) || !file.endsWith('.js')) continue;
    drifted.push(`${file} (stale)`);
    if (!check) fs.unlinkSync(path.join(OUT, file));
}

if (check && drifted.length) {
    console.error('src/functions is out of sync with flows.json:');
    drifted.forEach((f) => console.error(`  - ${f}`));
    process.exit(1);
}

console.log(
    check
        ? `${expected.size} function nodes in sync.`
        : `Wrote ${expected.size} function nodes to src/functions/ (${drifted.length} changed).`
);
